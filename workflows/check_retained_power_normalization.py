def _fixture_geometry(points: int = 48) -> dict[str, np.ndarray]:
    half = points // 2
    ap = np.linspace(0.0, 1.0, half)
    pd = np.mod(np.arange(half), 5) / 4.0
    left = np.column_stack((-0.02 * np.ones(half), -0.03 + 0.06 * ap, 0.01 * pd))
    right = left.copy()
    right[:, 0] *= -1.0
    return {
        "positions_m": np.vstack((left, right)),
        "longitudinal_coordinate": np.concatenate((ap, ap)),
        "proximal_distal_coordinate": np.concatenate((pd, pd)),
        "hemisphere_code": np.concatenate(
            (-np.ones(half, dtype=np.int8), np.ones(half, dtype=np.int8))
        ),
        "area_weights_m2": np.linspace(0.8, 1.2, points),
        "directions": np.tile(np.array([0.0, 0.0, 1.0]), (points, 1)),
    }


def _write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    fields: list[str] = []
    for row in rows:
        for key in row:
            if key not in fields:
                fields.append(key)
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, extrasaction="raise")
        writer.writeheader()
        writer.writerows(rows)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


