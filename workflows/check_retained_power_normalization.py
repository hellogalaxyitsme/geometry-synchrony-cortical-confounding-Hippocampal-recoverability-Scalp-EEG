class DeclaredInputResolutionTests(unittest.TestCase):
    def test_container_forward_path_resolves_under_forward_root(self) -> None:
        resolution = resolve_declared_input(
            "123456",
            "/forward/123456/hippunfold-hippocampal-fixed-leadfield.npy",
            Path("derivatives/forward"),
        )
        self.assertTrue(resolution.resolved_from_container)
        self.assertEqual(
            resolution.declared,
            "/forward/123456/hippunfold-hippocampal-fixed-leadfield.npy",
        )
        host = Path(resolution.host_path)
        self.assertEqual(host.name, "hippunfold-hippocampal-fixed-leadfield.npy")
        self.assertEqual(host.parent.name, "123456")
        self.assertEqual(host.parent.parent, Path("derivatives/forward"))

    def test_declared_subject_identity_overrides_container_subject(self) -> None:
        resolution = resolve_declared_input(
            "999999",
            "/forward/123456/hippunfold-hippocampal-source-metadata.npz",
            Path("/mnt/forward"),
        )
        self.assertTrue(resolution.resolved_from_container)
        self.assertEqual(Path(resolution.host_path).parent.name, "999999")
        self.assertEqual(
            Path(resolution.host_path).name,
            "hippunfold-hippocampal-source-metadata.npz",
        )

    def test_host_path_is_used_verbatim(self) -> None:
        declared = str(Path(tempfile.gettempdir()) / "forward" / "123456" / "file.npy")
        resolution = resolve_declared_input("123456", declared, Path("/other"))
        self.assertFalse(resolution.resolved_from_container)
        self.assertEqual(resolution.declared, declared)
        self.assertEqual(str(resolution.host_path), declared)

    def test_container_path_without_file_name_is_excluded(self) -> None:
        with self.assertRaises(AuditError):
            resolve_declared_input("123456", "/forward/123456/", Path("derivatives/forward"))


class NormalizationIdentityTests(unittest.TestCase):
    def setUp(self) -> None:
        self.generator = np.random.default_rng(20260921)

    def test_aligned_identical_columns_reach_unit_ratio(self) -> None:
        columns = np.tile(self.generator.normal(size=(9, 1)), (1, 6))
        areas = self.generator.uniform(0.5, 2.0, size=6)
        z_power, trace, ratio = retained_power(
            columns, areas, np.ones(6, dtype=np.complex128)
        )
        self.assertAlmostEqual(ratio, 1.0, places=14)
        self.assertAlmostEqual(z_power, trace, places=12)

    def test_exact_cancellation_reaches_zero_ratio(self) -> None:
        column = self.generator.normal(size=(9, 1))
        columns = np.column_stack((column, -column))
        _, trace, ratio = retained_power(
            columns, np.array([1.0, 1.0]), np.ones(2, dtype=np.complex128)
        )
        self.assertGreater(trace, 0.0)
        self.assertLessEqual(abs(ratio), 1e-15)

    def test_leadfield_scale_invariance(self) -> None:
        columns = self.generator.normal(size=(8, 5))
        phase = unit_phase_from_angles(self.generator.uniform(0, 2 * math.pi, 5))
        areas = self.generator.uniform(0.4, 3.0, size=5)
        _, trace, ratio = retained_power(columns, areas, phase)
        scaled_z, scaled_trace, scaled_ratio = retained_power(
            12.0 * columns, areas, phase
        )
        self.assertAlmostEqual(ratio, scaled_ratio, places=14)
        self.assertAlmostEqual(scaled_trace, 144.0 * trace, places=10)
        full_trace = float(
            np.dot(np.full(5, 0.2), np.sum(columns * columns, axis=0))
        )
        self.assertAlmostEqual(
            whole_sheet_power(scaled_z, 0.4, 144.0 * full_trace),
            whole_sheet_power(trace * ratio, 0.4, full_trace),
            places=13,
        )

    def test_uniform_raw_area_scale_invariance(self) -> None:
        columns = self.generator.normal(size=(8, 5))
        phase = unit_phase_from_angles(self.generator.uniform(0, 2 * math.pi, 5))
        areas = self.generator.uniform(0.4, 3.0, size=5)
        base_z, base_trace, base_ratio = retained_power(columns, areas, phase)
        scaled_z, scaled_trace, scaled_ratio = retained_power(
            columns, 6.5 * areas, phase
        )
        self.assertAlmostEqual(base_ratio, scaled_ratio, places=14)
        self.assertAlmostEqual(base_trace, scaled_trace, places=12)
        self.assertAlmostEqual(base_z, scaled_z, places=12)

    def test_mesh_split_of_identical_columns(self) -> None:
        columns = self.generator.normal(size=(8, 4))
        phase = unit_phase_from_angles(self.generator.uniform(0, 2 * math.pi, 4))
        areas = np.array([0.5, 1.5, 0.75, 0.25])
        base_z, base_trace, base_ratio = retained_power(columns, areas, phase)
        split_columns = np.column_stack(
            (columns[:, 0][:, None], columns[:, 0][:, None], columns[:, 1:])
        )
        split_areas = np.array([0.25, 0.25, 1.5, 0.75, 0.25])
        split_phase = np.concatenate(([phase[0], phase[0]], phase[1:]))
        split_z, split_trace, split_ratio = retained_power(
            split_columns, split_areas, split_phase
        )
        self.assertAlmostEqual(base_ratio, split_ratio, places=14)
        self.assertAlmostEqual(base_trace, split_trace, places=12)
        self.assertAlmostEqual(base_z, split_z, places=12)

    def test_weighted_jensen_bound_and_extremes(self) -> None:
        columns = np.tile(self.generator.normal(size=(10, 1)), (1, 4))
        areas = self.generator.uniform(0.2, 4.0, size=4)
        self.assertAlmostEqual(
            retained_power(columns, areas, np.ones(4, dtype=np.complex128))[2],
            1.0,
            places=14,
        )
        for _ in range(32):
            random_columns = self.generator.normal(size=(10, 7))
            random_phase = unit_phase_from_angles(
                self.generator.uniform(0, 2 * math.pi, 7)
            )
            random_areas = self.generator.uniform(0.1, 5.0, size=7)
            ratio = retained_power(random_columns, random_areas, random_phase)[2]
            self.assertGreaterEqual(ratio, 0.0)
            self.assertLessEqual(ratio, 1.0 + 1e-12)

    def test_independent_phase_expectation_differs_from_reference(self) -> None:
        columns = self.generator.normal(size=(6, 7))
        areas = np.array([0.40, 0.24, 0.14, 0.10, 0.06, 0.04, 0.02])
        analytic = independent_phase_power(columns, areas)
        trials = 200000
        phase = unit_phase_from_angles(
            self.generator.uniform(0.0, 2.0 * math.pi, size=(trials, 7))
        )
        quadrature = phase * (areas / np.sum(areas))[None, :]
        field = quadrature @ columns.T
        monte_carlo = float(np.mean(np.sum(field * field.conjugate(), axis=1).real))
        self.assertLess(abs(monte_carlo - analytic) / analytic, 0.01)
        _, incoherent, _ = retained_power(
            columns, areas, np.ones(7, dtype=np.complex128)
        )
        self.assertGreater(abs(analytic - incoherent) / incoherent, 0.1)

    def test_uniform_conditional_weights_give_reference_over_n(self) -> None:
        columns = self.generator.normal(size=(6, 9))
        counts = (2, 5, 9)
        for count in counts:
            areas = np.ones(count, dtype=np.float64)
            expectation = independent_phase_power(columns[:, :count], areas)
            _, reference, _ = retained_power(
                columns[:, :count], areas, np.ones(count, dtype=np.complex128)
            )
            self.assertAlmostEqual(expectation, reference / count, places=14)
            self.assertLess(expectation, reference)
            self.assertAlmostEqual(expectation / reference, 1.0 / count, places=14)
        # Corroborate the 1/N factor by Monte Carlo at one uniform N > 1.
        count = 5
        areas = np.ones(count, dtype=np.float64)
        _, reference, _ = retained_power(
            columns[:, :count], areas, np.ones(count, dtype=np.complex128)
        )
        trials = 200000
        phase = unit_phase_from_angles(
            self.generator.uniform(0.0, 2.0 * math.pi, size=(trials, count))
        )
        field = (phase * (areas / np.sum(areas))[None, :]) @ columns[:, :count].T
        monte_carlo = float(np.mean(np.sum(field * field.conjugate(), axis=1).real))
        self.assertLess(abs(monte_carlo - reference / count) / (reference / count), 0.01)

    def test_whole_sheet_scaling_with_area_fraction(self) -> None:
        columns = self.generator.normal(size=(8, 5))
        phase = unit_phase_from_angles(self.generator.uniform(0, 2 * math.pi, 5))
        areas = self.generator.uniform(0.4, 3.0, size=5)
        z_power, trace, ratio = retained_power(columns, areas, phase)
        full_trace = float(
            np.dot(np.full(5, 0.2), np.sum(columns * columns, axis=0))
        )
        fraction = 0.25
        direct = whole_sheet_power(z_power, fraction, full_trace)
        composed = fraction**2 * ratio * trace / full_trace
        self.assertAlmostEqual(direct, composed, places=14)
        self.assertAlmostEqual(
            whole_sheet_power(z_power, 2.0 * fraction, full_trace), 4.0 * direct, places=13
        )

    def test_module_identity_suite_passes(self) -> None:
        records = synthetic_identity_checks()
        self.assertTrue(synthetic_checks_passed(records))
        self.assertEqual(len(records), 9)


